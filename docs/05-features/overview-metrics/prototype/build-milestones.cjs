// Reuses the existing frozen React/Lucide vendor; only this screen is bundled.
const fs = require('node:fs')
const path = require('node:path')
const esbuild = require('esbuild')
const output = path.join(__dirname, 'milestones.js')
const result = esbuild.buildSync({
  entryPoints: [path.join(__dirname, 'milestones.jsx')],
  bundle: true,
  write: false,
  format: 'iife',
  platform: 'browser',
  jsxFactory: 'React.createElement',
  jsxFragment: 'React.Fragment',
  charset: 'utf8',
  minifyWhitespace: true,
  minifyIdentifiers: true,
  banner: {
    js: '/* Generated by build-milestones.cjs. Edit milestones*.jsx. */\n/* eslint-disable */\n// prettier-ignore'
  }
}).outputFiles[0].text
if (process.argv.includes('--check')) {
  if (
    !fs.existsSync(output) ||
    fs.readFileSync(output, 'utf8').replace(/\r\n/g, '\n') !== result.replace(/\r\n/g, '\n')
  ) {
    throw new Error('Run node prototype/build-milestones.cjs to rebuild the milestone prototype.')
  }
  console.log('Milestone prototype matches editable source.')
} else {
  fs.writeFileSync(output, result)
}
