import { readFileSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { createHash } from 'node:crypto'

const root = import.meta.dirname
const read = (file) => readFileSync(file, 'utf8').replaceAll('\r\n', '\n')
const source = read(join(root, 'source.html'))
const system = read(resolve(root, '../../../04-design-system/styles.css'))
const css = read(join(root, 'prototype.css'))
const js = read(join(root, 'prototype.js'))
const hash = createHash('sha256')
  .update(source + system + css + js)
  .digest('hex')
const html = source
  .replace(
    '<!doctype html>',
    `<!doctype html>\n<!-- GENERATED by build.mjs. Edit source.html / prototype.css / prototype.js. Design tokens: docs/04-design-system/styles.css. Source SHA256: ${hash} -->`
  )
  .replace(
    /<link\b[^>]*href="\.\.\/\.\.\/\.\.\/04-design-system\/styles.css"[^>]*>\s*<link\b[^>]*href="prototype.css"[^>]*>/,
    `<style>\n${system}\n${css}\n</style>`
  )
  .replace(
    /<script\b[^>]*src="prototype.js"[^>]*><\/script>/,
    `<script>\n${js.replaceAll('</script', '<\\/script')}\n</script>`
  )
if (
  /<link\b[^>]*rel="stylesheet"|<script\b[^>]*src=/.test(html) ||
  !html.includes('<style>') ||
  !html.includes('<script>')
) {
  throw new Error('Build markers did not produce a standalone document.')
}
const output = join(root, 'prototype.html')
if (process.argv.includes('--check')) {
  if (read(output) !== html) {
    process.stderr.write('Prototype projection is stale. Run build.mjs.\n')
    process.exitCode = 1
  }
} else {
  writeFileSync(output, html)
  process.stdout.write('Built standalone prototype.html\n')
}
