// Builds the #461 CI screen review candidate bundle from ci-app.jsx / ci-model.js.
const fs = require('node:fs')
const path = require('node:path')
const esbuild = require('esbuild')
const out = path.join(__dirname, 'ci-journey.js')
esbuild
  .build({
    entryPoints: [path.join(__dirname, 'ci-app.jsx')],
    bundle: true,
    write: false,
    format: 'iife',
    platform: 'browser',
    jsxFactory: 'React.createElement',
    jsxFragment: 'React.Fragment',
    charset: 'utf8',
    minify: true,
    banner: {
      js: '/* Generated by build-ci.cjs; edit ci-app.jsx / ci-model.js instead. */\n/* eslint-disable */\n// prettier-ignore'
    }
  })
  .then(({ outputFiles }) => {
    const content = outputFiles[0].text
    if (process.argv.includes('--check')) {
      if (fs.readFileSync(out, 'utf8').replace(/\r\n/g, '\n') !== content) {
        throw new Error('CI screen prototype bundle is stale')
      }
      console.log('CI screen prototype bundle matches sources')
    } else {
      fs.writeFileSync(out, content)
      console.log('Built CI screen review candidate')
    }
  })
  .catch((error) => {
    console.error(error)
    process.exitCode = 1
  })
