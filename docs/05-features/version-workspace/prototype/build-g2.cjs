// Finalized-design entry shares the feature's frozen React/Lucide bundle.
const fs = require('node:fs')
const path = require('node:path')
const esbuild = require('esbuild')
const output = path.join(__dirname, 'g2-workspace.js')
const result = esbuild.buildSync({
  entryPoints: [path.join(__dirname, 'g2-workspace.jsx')],
  bundle: true,
  write: false,
  format: 'iife',
  platform: 'browser',
  jsxFactory: 'React.createElement',
  jsxFragment: 'React.Fragment',
  charset: 'utf8',
  minifyWhitespace: true,
  minifyIdentifiers: true,
  banner: {
    js: '/* Generated by build-g2.cjs. Edit g2-workspace.jsx, not this file. */\n/* eslint-disable */\n// prettier-ignore'
  }
}).outputFiles[0].text
if (process.argv.includes('--check')) {
  if (
    !fs.existsSync(output) ||
    fs.readFileSync(output, 'utf8').replace(/\r\n/g, '\n') !== result.replace(/\r\n/g, '\n')
  ) {
    throw new Error('G2 prototype bundle is stale. Run node prototype/build-g2.cjs.')
  }
  console.log('G2 prototype bundle matches source.')
} else {
  fs.writeFileSync(output, result)
}
