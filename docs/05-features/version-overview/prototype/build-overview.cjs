// Reuse the existing frozen React/Lucide bundle; this build owns only #334's UI.
const fs = require('node:fs')
const path = require('node:path')
const esbuild = require('esbuild')
const output = path.join(__dirname, 'overview.js')
const result = esbuild.buildSync({
  entryPoints: [path.join(__dirname, 'overview-app.jsx')],
  bundle: true,
  write: false,
  format: 'iife',
  platform: 'browser',
  jsxFactory: 'React.createElement',
  jsxFragment: 'React.Fragment',
  charset: 'utf8',
  minify: true,
  banner: {
    js: '/* Generated by build-overview.cjs; edit overview-*.jsx. */\n/* eslint-disable */\n// prettier-ignore'
  }
}).outputFiles[0].text
if (process.argv.includes('--check')) {
  if (!fs.existsSync(output) || fs.readFileSync(output, 'utf8').replace(/\r\n/g, '\n') !== result) {
    throw new Error('Overview bundle is stale: run build-overview.cjs')
  }
  console.log('Overview bundle matches editable sources.')
} else {
  fs.writeFileSync(output, result)
}
