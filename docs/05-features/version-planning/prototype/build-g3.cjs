// Builds only the G3 candidate; the approved shared planning/acceptance baseline stays unchanged.
const fs = require('node:fs')
const path = require('node:path')
const esbuild = require('esbuild')
const out = path.join(__dirname, 'g3-planning.js')
esbuild
  .build({
    entryPoints: [path.join(__dirname, 'g3-app.jsx')],
    bundle: true,
    write: false,
    format: 'iife',
    platform: 'browser',
    jsxFactory: 'React.createElement',
    jsxFragment: 'React.Fragment',
    charset: 'utf8',
    minify: true,
    banner: {
      js: '/* Generated by build-g3.cjs; edit g3-*.jsx instead. */\n/* eslint-disable */\n// prettier-ignore'
    }
  })
  .then(({ outputFiles }) => {
    const content = outputFiles[0].text
    if (process.argv.includes('--check')) {
      if (fs.readFileSync(out, 'utf8') !== content) throw new Error('G3 prototype bundle is stale')
      console.log('G3 prototype bundle matches sources')
    } else {
      fs.writeFileSync(out, content)
      console.log('Built G3 planning candidate')
    }
  })
  .catch((error) => {
    console.error(error)
    process.exitCode = 1
  })
