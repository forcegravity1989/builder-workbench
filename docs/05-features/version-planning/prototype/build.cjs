// Rebuild the three offline entries from their feature-owned JSX sources.
// The frozen v8 dependency bundle is deliberately separate from editable UI.
const fs = require('node:fs')
const path = require('node:path')
const esbuild = require('esbuild')

const output = path.join(__dirname, 'runtime.js')
const check = process.argv.includes('--check')
const dependencies = {
  react: ['React', 'useState', 'useRef', 'useEffect'],
  'react-dom/client': ['createRoot'],
  'react-markdown': ['ReactMarkdown'],
  'remark-gfm': ['remarkGfm'],
  'lucide-react': [
    'GitCommitHorizontal',
    'Inbox',
    'Info',
    'ArrowRight',
    'ArrowUpRight',
    'LayoutDashboard',
    'CalendarRange',
    'ListTodo',
    'ClipboardCheck',
    'CalendarClock',
    'BookOpen',
    'GitBranch',
    'MessageSquare',
    'History',
    'Plus',
    'ChevronDown',
    'ChevronRight',
    'ArrowUp',
    'ArrowLeft',
    'Target',
    'Presentation',
    'BrainCircuit',
    'GitPullRequest',
    'ClipboardList',
    'PackageCheck',
    'ChartNoAxesCombined',
    'Pencil',
    'X',
    'ExternalLink',
    'CircleHelp',
    'RefreshCw',
    'Check',
    'Copy'
  ]
}

esbuild
  .build({
    entryPoints: [path.join(__dirname, 'app.jsx')],
    bundle: true,
    write: false,
    format: 'iife',
    platform: 'browser',
    jsxFactory: 'React.createElement',
    jsxFragment: 'React.Fragment',
    charset: 'utf8',
    minifyWhitespace: true,
    minifyIdentifiers: true,
    banner: {
      js: '/* Generated by prototype/build.cjs. Edit feature JSX, not this file. */\n/* eslint-disable */\n// prettier-ignore'
    },
    plugins: [
      {
        name: 'frozen-v8-dependencies',
        setup(build) {
          build.onResolve(
            { filter: /^(react|react-dom\/client|react-markdown|remark-gfm|lucide-react)$/ },
            (args) => ({
              path: args.path,
              namespace: 'v8'
            })
          )
          build.onLoad({ filter: /.*/, namespace: 'v8' }, (args) => ({
            contents: dependencies[args.path]
              .map((name) => `export const ${name} = window.BWPrototypeDependencies.${name};`)
              .join('\n')
          }))
        }
      }
    ]
  })
  .then((result) => {
    const text = result.outputFiles[0].text
    if (check) {
      if (fs.readFileSync(output, 'utf8') !== text) {
        throw new Error('Prototype runtime is stale; rebuild it.')
      }
      console.log('Prototype runtime matches its sources.')
    } else {
      fs.writeFileSync(output, text)
      console.log('Rebuilt prototype/runtime.js for all three offline entries.')
    }
  })
  .catch((error) => {
    console.error(error.message)
    process.exitCode = 1
  })
