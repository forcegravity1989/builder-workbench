import fs from 'node:fs'
import path from 'node:path'
import { transform } from 'esbuild'
import { format } from 'oxfmt'

const sourcePath = path.join(import.meta.dirname, 'charter-demo.jsx')
const outputPath = path.join(import.meta.dirname, 'charter-demo.js')
const { code } = await transform(fs.readFileSync(sourcePath, 'utf8'), {
  loader: 'jsx',
  charset: 'utf8',
  format: 'iife'
})
const configPath = path.resolve(import.meta.dirname, '../../../../.oxfmtrc.json')
const config = JSON.parse(fs.readFileSync(configPath, 'utf8'))
const { code: generated, errors } = await format(
  outputPath,
  `// Generated by build-charter-demo.mjs from charter-demo.jsx.\n${code}`,
  config
)
if (errors.length) {
  throw new Error(errors.map(({ message }) => message).join('\n'))
}

if (process.argv.includes('--check')) {
  if (fs.readFileSync(outputPath, 'utf8').replaceAll('\r\n', '\n') !== generated) {
    throw new Error('Rebuild the charter demo from charter-demo.jsx.')
  }
} else {
  fs.writeFileSync(outputPath, generated)
}
